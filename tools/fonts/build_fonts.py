"""Antialiased fonts for the keypad: B612 (OFL, Airbus/Intactile's cockpit face)
rasterized into VLW, the smooth-font format LovyanGFX draws.

    python tools/fonts/build_fonts.py      ->  firmware/TouchKeypad/fonts_gen.h

VLW: big-endian int32 header (glyph count, version 11, size, 0, ascent, descent),
7 int32 per glyph (unicode, height, width, x advance, top above baseline, left
offset, 0), then each glyph's 8-bit alpha bitmap in order.
"""
import struct
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
SRC = HERE / "src"
OUT = HERE.parents[1] / "firmware" / "TouchKeypad" / "fonts_gen.h"

TEXT = "".join(chr(c) for c in range(0x20, 0x7F)) + "·…›–°×"
DIGITS = " 0123456789:%-+."

# name, file, pixel size, glyph set
FONTS = [
    ("FONT_LABEL", "B612-Regular.ttf", 13, TEXT),        # key labels, secondary text
    ("FONT_BODY", "B612-Regular.ttf", 15, TEXT),         # sheet rows, toasts
    ("FONT_BODY_B", "B612-Bold.ttf", 15, TEXT),          # tabs, buttons, status
    ("FONT_TITLE", "B612-Bold.ttf", 19, TEXT),           # clock, sheet titles
    ("FONT_HEAD", "B612-Bold.ttf", 25, TEXT),            # media title
    ("FONT_READOUT", "B612Mono-Regular.ttf", 13, TEXT),  # times, values, readouts
    ("FONT_DIGITS", "B612Mono-Bold.ttf", 46, DIGITS),    # passkey, volume level
]


def vlw(ttf, px, chars):
    font = ImageFont.truetype(str(SRC / ttf), px)
    ascent, descent = font.getmetrics()
    glyphs, bitmaps = [], []
    for ch in sorted(set(chars), key=ord):
        adv = round(font.getlength(ch))
        l, t, r, b = font.getbbox(ch, anchor="ls")
        w, h = max(0, r - l), max(0, b - t)
        if ch == " " or w == 0 or h == 0:
            glyphs.append((ord(ch), 0, 0, adv, 0, 0))
            continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor="ls")
        glyphs.append((ord(ch), h, w, adv, -t, l))
        bitmaps.append(img.tobytes())
    out = struct.pack(">6i", len(glyphs), 11, px, 0, ascent, descent)
    for g in glyphs:
        out += struct.pack(">7i", *g, 0)
    return out + b"".join(bitmaps)


def c_array(name, data):
    rows = [",".join(f"0x{b:02x}" for b in data[i:i + 24]) for i in range(0, len(data), 24)]
    return f"static const uint8_t {name}[] PROGMEM = {{\n  " + ",\n  ".join(rows) + "\n};\n"


def main():
    parts = ["// Generated by tools/fonts/build_fonts.py from B612 (SIL OFL 1.1). Do not edit.\n#pragma once\n#include <Arduino.h>\n"]
    total = 0
    for name, ttf, px, chars in FONTS:
        data = vlw(ttf, px, chars)
        total += len(data)
        parts.append(c_array(name, data))
        print(f"{name:13} {ttf:22} {px:3}px {len(data):6} B")
    OUT.write_text("\n".join(parts))
    print(f"total {total} B -> {OUT}")


if __name__ == "__main__":
    main()
